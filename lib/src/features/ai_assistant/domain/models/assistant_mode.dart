/// 定义AI助手的工作模式
/// 
/// 创建时间: 2023-03-15
/// 最后修改: 2023-03-15
/// 
/// 包含三种模式:
/// - guardian: 守护模式，提供基础保护和监控功能
/// - standard: 标准模式，提供日常使用的功能
/// - pro: 专业模式，提供高级功能和定制选项

enum AssistantMode {
  /// 守护模式 - 提供基础保护和监控功能
  guardian,
  
  /// 标准模式 - 提供日常使用的功能
  standard,
  
  /// 专业模式 - 提供高级功能和定制选项
  pro,
} 